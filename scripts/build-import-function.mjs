// Bundles the recipe import helper (src/import/importHandler.ts and the recipe
// parser it uses) into one file for the Supabase Edge Function "import-recipe",
// so it can be pasted into the Supabase dashboard or deployed with the CLI.
// Run after changing the import code: npm run build:import-function
import { build } from 'esbuild';

const banner = `// GENERATED by \`npm run build:import-function\` from src/import/importHandler.ts. Don't edit by hand.
// Supabase Edge Function "import-recipe": the web app's recipe import helper.
// Deployed by the "Deploy import helper" GitHub workflow. By hand: Supabase dashboard → Edge Functions →
// Deploy a new function → Via editor, name it import-recipe, paste this file over index.ts.
// @ts-nocheck`;

await build({
  stdin: {
    contents: "import { handleImport } from './src/import/importHandler';\nDeno.serve(handleImport);\n",
    resolveDir: process.cwd(),
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  alias: { '@': '.' },
  banner: { js: banner },
  legalComments: 'none',
  outfile: 'supabase/functions/import-recipe/index.ts',
  logLevel: 'info',
});
